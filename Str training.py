print('Привет!')
while True:
    print(f"Выбери уровень:  1, 2, 3, 4 или 5 -> \nДля окончания программы введи 0.")
    try:
        u = int(input())
    except ValueError:
        print("Ошибка: введи число.")
        continue

    if u == 0:
        print(f"Пока!")
        break

    elif u == 1:
        print(f"Описание уровня:\nМетод 1: upper() - Переводит всю строку в верхний регистр.\nМетод 2: lower() - Переводит всю строку в нижний регистр.\nМетод 3: capitalize() - Делает заглавной только первую букву, остальные — строчными.\n")
        t = "пРиВет МИР!"
        print(f"Проведем тест на строке '{t}':\nРезультат метода 1: {t.upper()} <- Все символы стали заглавными.\nРезультат метода 2: {t.lower()} <- Все символы стали строчными.\nРезультат метода 3: {t.capitalize()} <- Первая буква заглавная, остальные строчные.\n")
        try:
            m = int(input("Выбери метод: "))
        except ValueError:
            print("Ошибка: введи число.")
            continue
        if m == 1:
            a = input("Введи строку: ")
            print("Результат: ", a.upper())
        elif m == 2:
            b = input("Введи строку: ")
            print("Результат: ", b.lower())
        elif m == 3:
            c = input("Введи строку: ")
            print("Результат: ", c.capitalize())
        else:
            print("Ошибка")

    elif u == 2:
        print(f"Описание уровня:\nМетод 1: find() - Возвращает позицию первого вхождения искомого фрагмента.\nМетод 2: replace() - Меняет один фрагмент строки на другой.\nМетод 3: count() - Подсчитывает, сколько раз символ встречается в строке.\n")
        t = "Ботать это круто. Очень круто"
        print(f"Проведем тест на строке '{t}':\nРезультат метода 1: {t.find('круто')} <- Позиция первого слова 'круто'.\nРезультат метода 2: {t.replace('круто', '+')} <- Вместо 'круто' теперь стоит '+'.\nРезультат метода 3: {t.count('о')} <- Количество символов 'о' в строке.\n")
        try:
            m = int(input("Выбери метод: "))
        except ValueError:
            print("Ошибка: введи число.")
            continue
        if m == 1:
            a = input("Введи строку: ")
            s = input("Введи символ/слово, позицию которого хочешь узнать: ")
            print("Результат: ", a.find(s))
        elif m == 2:
            b = input("Введи строку: ")
            s = input("Введи символ/слово, которое нужно заменить: ")
            k = input("Введи символ/слово для замены: ")
            print("Результат: ", b.replace(s, k))
        elif m == 3:
            c = input("Введи строку: ")
            s = input("Введи символ, частоту которого нужно посчитать: ")
            print("Результат: ", c.count(s))
        else:
            print("Ошибка")

    elif u == 3:
        print(f"Описание уровня:\nМетод 1: split() - Делит строку на список элементов по указанному разделителю.\nМетод 2: join() - Объединяет элементы последовательности в одну строку через разделитель.\n")
        t = "1,2,3,4"
        parts = t.split(",")
        print(f"Проведем тест на строке '{t}':\nМетод 1: {parts} <- Получили список элементов, разделенных ','.\nМетод 2: {' '.join(parts)} <- Элементы списка объединены пробелом.\n")
        try:
            m = int(input("Выбери метод: "))
        except ValueError:
            print("Ошибка: введи число.")
            continue
        if m == 1:
            a = input("Введи строку: ")
            s = input("Введи разделитель для создания списка: ")
            print("Результат: ", a.split(s))
        elif m == 2:
            b = input("Введи последовательность (символы будут объединены): ")
            s = input("Введи разделитель для объединения: ")
            print("Результат: ", s.join(b))
        else:
            print("Ошибка")

    elif u == 4:
        print(f"Описание уровня:\nМетод 1: isdigit() - Проверяет, состоит ли строка только из цифр (True/False)\nМетод 2: isalpha() - Проверяет, состоит ли строка только из букв (True/False)\nМетод 3: strip() - Удаляет указанные символы (по умолчанию пробелы) с начала и конца строки.\n")
        t = " 1234*&%1$    "
        print(f"Проведем тест на строке '{t}':\nМетод 1: {t.isdigit()} - False, так как в строке есть не только цифры\nМетод 2: {t.isalpha()} - False, так как в строке есть не только буквы\nМетод 3: '{t.strip()}' - строка очищена от лишних символов по краям.\n")
        try:
            m = int(input("Выбери метод: "))
        except ValueError:
            print("Ошибка: введи число.")
            continue
        if m == 1:
            a = input("Введи строку: ")
            print("Результат: ", a.isdigit())
        elif m == 2:
            b = input("Введи строку: ")
            print("Результат: ", b.isalpha())
        elif m == 3:
            c = input("Введи строку: ")
            s = input("Введи символ для удаления по краям (Enter - пробелы): ")
            if s:
                print("Результат: ", c.strip(s))
            else:
                print("Результат: ", c.strip())
        else:
            print("Ошибка")

    elif u == 5:
        print(f"Описание уровня:\nЭтот уровень объединяет методы предыдущих уровней и приводит строку к аккуратному виду.\n")
        t = ".......pYtHon;is;AWESOME-------"
        a = t.strip('.-')
        b = a.replace(';', ' ')
        c = b.capitalize()
        print(f"Проведем тест на строке '{t}':\nШаг_1 (strip()): '{a}' - Срезали точки и дефисы по краям.\nШаг_2 (replace()): '{b}' - Заменили символы (;) на пробелы.\nШаг_3 (capitalize()): '{c}' - Привели к правильному регистру.\n")
        v = input("Введи строку: ")
        print("Если какое-то изменение не нужно — просто нажми Enter!")
        s = input("Введи символы для удаления по краям: ")
        if s:
            v = v.strip(s)
        k = input("Введи символ для замены: ")
        if k:
            n = input("Введи символ для подстановки: ")
            v = v.replace(k, n)
        print("Результат: ", v.capitalize())

    else:
        print("Ошибка: такого уровня нет.")
